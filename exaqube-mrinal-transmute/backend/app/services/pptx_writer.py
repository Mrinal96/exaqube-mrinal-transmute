"""Native editable PowerPoint rendering and package validation."""

import json
from io import BytesIO
from typing import Any

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.chart.data import CategoryChartData
from pptx.enum.chart import XL_CHART_TYPE
from pptx.enum.shapes import MSO_SHAPE
from pptx.oxml.xmlchemy import OxmlElement
from pptx.util import Inches, Pt

from app.models.artifacts import (
    ArtifactMetric,
    ArtifactTable,
    ArtifactText,
    PPTXArtifactContent,
    PPTXChartContent,
    PPTXChartElement,
    PPTXBulletsElement,
    PPTXCalloutElement,
    PPTXMetricElement,
    PPTXParagraphElement,
    PPTXTableElement,
    PPTXTitleElement,
)


MOCK_NOTICE = (
    "MOCK OUTPUT — no LLM interpretation or semantic transformation was performed. "
    "This file contains source content extracted from the uploaded document."
)


def render_pptx(
    content: PPTXArtifactContent,
    *,
    is_mock: bool,
    provenance: dict[str, Any],
) -> bytes:
    """Render editable PowerPoint shapes and preserve citations/provenance in notes."""
    presentation = Presentation()
    presentation.core_properties.title = content.presentation_title
    presentation.core_properties.subject = "Generated by Transmute"
    blank_layout = presentation.slide_layouts[6]

    for slide_content in content.slides:
        slide = presentation.slides.add_slide(blank_layout)
        _add_title(slide, slide_content.title, Inches(0.55), Inches(0.35), Inches(12.2), Inches(0.7))
        y = Inches(1.25)
        bottom = presentation.slide_height - Inches(0.5)
        if slide_content.title_source_references:
            title_citation = slide.shapes.add_textbox(Inches(0.58), Inches(1.02), Inches(12), Inches(0.18))
            paragraph = title_citation.text_frame.paragraphs[0]
            paragraph.text = "Source: " + ", ".join(
                reference.block_id or reference.section_id or "source"
                for reference in slide_content.title_source_references
            )
            paragraph.font.size = Pt(8)
            paragraph.font.color.rgb = RGBColor(95, 107, 126)

        for element in slide_content.elements:
            if isinstance(element, PPTXTitleElement):
                y = _add_text_item(slide, element.content, y, bottom, size=20, bold=True)
            elif isinstance(element, (PPTXParagraphElement, PPTXCalloutElement)):
                y = _add_text_item(
                    slide,
                    element.content,
                    y,
                    bottom,
                    size=15,
                    callout=isinstance(element, PPTXCalloutElement),
                )
            elif isinstance(element, PPTXBulletsElement):
                y = _add_bullets(slide, element.items, y, bottom)
            elif isinstance(element, PPTXTableElement):
                y = _add_table(slide, element.content, y, bottom)
            elif isinstance(element, PPTXMetricElement):
                y = _add_metric(slide, element.content, y, bottom)
            elif isinstance(element, PPTXChartElement):
                y = _add_chart(slide, element.content, y, bottom)
            else:  # Defensive guard for values introduced outside the Pydantic union.
                raise ValueError("Unsupported PPTX artifact element.")

        if is_mock:
            notice = slide.shapes.add_textbox(
                Inches(0.55), presentation.slide_height - Inches(0.34), Inches(12.2), Inches(0.22)
            )
            paragraph = notice.text_frame.paragraphs[0]
            paragraph.text = MOCK_NOTICE
            paragraph.font.size = Pt(8)
            paragraph.font.italic = True
            paragraph.font.color.rgb = RGBColor(110, 83, 33)

        slide.notes_slide.notes_text_frame.text = _slide_notes(slide_content, provenance)

    output = BytesIO()
    presentation.save(output)
    return output.getvalue()


def validate_pptx_output(content: bytes) -> None:
    """Re-open the package and reject empty or structurally empty presentations."""
    if not content:
        raise ValueError("The PPTX renderer produced an empty file.")
    try:
        presentation = Presentation(BytesIO(content))
    except Exception as exc:
        raise ValueError("The rendered PPTX is not a valid PowerPoint package.") from exc
    if not presentation.slides:
        raise ValueError("The rendered PPTX must contain at least one slide.")
    for index, slide in enumerate(presentation.slides, start=1):
        has_content = any(
            (shape.has_text_frame and bool(shape.text.strip())) or shape.has_table or shape.has_chart
            for shape in slide.shapes
        )
        if not has_content:
            raise ValueError(f"Rendered PPTX slide {index} contains no visible content.")


def _add_title(slide, title: str, left, top, width, height) -> None:
    shape = slide.shapes.add_textbox(left, top, width, height)
    shape.text_frame.word_wrap = True
    paragraph = shape.text_frame.paragraphs[0]
    paragraph.text = title
    paragraph.font.size = Pt(26)
    paragraph.font.bold = True
    paragraph.font.color.rgb = RGBColor(27, 39, 64)


def _add_text_item(slide, item: ArtifactText, y, bottom, *, size: int, bold: bool = False, callout: bool = False):
    height = Inches(0.78 if len(item.text) < 150 else 1.15)
    _check_room(y, height + Inches(0.25), bottom)
    left = Inches(0.68)
    width = Inches(11.95)
    if callout:
        shape = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, left, y, width, height)
        shape.fill.solid()
        shape.fill.fore_color.rgb = RGBColor(232, 245, 243)
        shape.line.color.rgb = RGBColor(126, 190, 180)
        frame = shape.text_frame
    else:
        shape = slide.shapes.add_textbox(left, y, width, height)
        frame = shape.text_frame
    frame.word_wrap = True
    frame.text = item.text
    for paragraph in frame.paragraphs:
        paragraph.font.size = Pt(size)
        paragraph.font.bold = bold
        paragraph.font.color.rgb = RGBColor(38, 49, 67)
    _add_visible_source(slide, item, y + height)
    return y + height + Inches(0.25)


def _add_bullets(slide, items: list[ArtifactText], y, bottom):
    height = Inches(0.42 * len(items))
    for item in items:
        height += Inches(0.2 * max(0, len(item.text) // 95))
    _check_room(y, height + Inches(0.25), bottom)
    shape = slide.shapes.add_textbox(Inches(0.8), y, Inches(11.7), height)
    frame = shape.text_frame
    frame.clear()
    frame.word_wrap = True
    for index, item in enumerate(items):
        paragraph = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
        paragraph.text = item.text
        paragraph.level = 0
        paragraph.font.size = Pt(15)
        p_pr = paragraph._p.get_or_add_pPr()
        bullet = OxmlElement("a:buChar")
        bullet.set("char", "•")
        p_pr.append(bullet)
        citation = frame.add_paragraph()
        citation.text = _source_label(item)
        citation.font.size = Pt(8)
        citation.font.color.rgb = RGBColor(95, 107, 126)
    return y + height + Inches(0.25)


def _add_table(slide, table_data: ArtifactTable, y, bottom):
    row_count = len(table_data.rows) + 1
    height = Inches(max(0.38 * row_count, 0.5))
    extra = Inches(0.28 if table_data.caption else 0)
    _check_room(y, height + extra + Inches(0.26), bottom)
    if table_data.caption:
        caption = slide.shapes.add_textbox(Inches(0.65), y, Inches(12), Inches(0.25))
        caption.text_frame.text = table_data.caption
        caption.text_frame.paragraphs[0].font.size = Pt(10)
        caption.text_frame.paragraphs[0].font.italic = True
        y += extra
    shape = slide.shapes.add_table(
        row_count,
        len(table_data.headers),
        Inches(0.65),
        y,
        Inches(12),
        height,
    )
    table = shape.table
    for column, value in enumerate(table_data.headers):
        cell = table.cell(0, column)
        cell.text = value
        cell.fill.solid()
        cell.fill.fore_color.rgb = RGBColor(230, 235, 244)
        _style_table_cell(cell, bold=True)
    for row_index, row in enumerate(table_data.rows, start=1):
        for column, value in enumerate(row):
            cell = table.cell(row_index, column)
            cell.text = value
            _style_table_cell(cell)
    _add_visible_source(slide, table_data, y + height)
    return y + height + Inches(0.25)


def _add_metric(slide, metric: ArtifactMetric, y, bottom):
    height = Inches(0.9)
    _check_room(y, height + Inches(0.25), bottom)
    shape = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE, Inches(0.68), y, Inches(5.5), height
    )
    shape.fill.solid()
    shape.fill.fore_color.rgb = RGBColor(238, 243, 250)
    shape.line.color.rgb = RGBColor(198, 209, 227)
    frame = shape.text_frame
    frame.text = metric.name
    value_paragraph = frame.add_paragraph()
    value_paragraph.text = _metric_value(metric)
    value_paragraph.font.size = Pt(18)
    value_paragraph.font.bold = True
    value_paragraph.font.color.rgb = RGBColor(50, 67, 102)
    _add_visible_source(slide, metric, y + height)
    return y + height + Inches(0.25)


def _add_chart(slide, chart_data: PPTXChartContent, y, bottom):
    """Create a native editable chart; None values are represented as data gaps."""
    height = Inches(4.8)
    citation_space = Inches(0.38)
    _check_room(y, height + citation_space, bottom)

    chart_type = {
        "bar": XL_CHART_TYPE.BAR_CLUSTERED,
        "line": XL_CHART_TYPE.LINE,
        "pie": XL_CHART_TYPE.PIE,
    }[chart_data.chart_type]
    data = CategoryChartData()
    data.categories = chart_data.categories
    for series in chart_data.series:
        data.add_series(series.name, series.values)

    shape = slide.shapes.add_chart(
        chart_type,
        Inches(0.72),
        y,
        Inches(11.9),
        height,
        data,
    )
    chart = shape.chart
    chart.has_title = True
    chart.chart_title.text_frame.text = chart_data.title
    chart.has_legend = True
    if chart_data.chart_type == "pie":
        plot = chart.plots[0]
        plot.has_data_labels = True
        plot.data_labels.show_category_name = True
        plot.data_labels.show_percentage = True
    _add_visible_source(slide, chart_data, y + height)
    return y + height + citation_space


def _style_table_cell(cell, *, bold: bool = False) -> None:
    for paragraph in cell.text_frame.paragraphs:
        paragraph.font.size = Pt(11)
        paragraph.font.bold = bold
        paragraph.font.color.rgb = RGBColor(35, 46, 65)


def _metric_value(metric: ArtifactMetric) -> str:
    parts = [f"{metric.currency or ''}{metric.value}", metric.unit, metric.reporting_period]
    return " · ".join(str(part) for part in parts if part)


def _add_visible_source(slide, item, y) -> None:
    label = _source_label(item)
    citation = slide.shapes.add_textbox(Inches(0.72), y, Inches(11.8), Inches(0.18))
    paragraph = citation.text_frame.paragraphs[0]
    paragraph.text = label
    paragraph.font.size = Pt(8)
    paragraph.font.color.rgb = RGBColor(95, 107, 126)


def _source_label(item) -> str:
    references = item.source_references
    return "Source: " + ", ".join(
        reference.block_id or reference.section_id or "source" for reference in references
    )


def _slide_notes(slide_content, provenance: dict[str, Any]) -> str:
    references: list[dict[str, Any]] = [
        reference.model_dump(mode="json", exclude_none=True)
        for reference in slide_content.title_source_references
    ]
    for element in slide_content.elements:
        values = []
        if isinstance(element, (PPTXTitleElement, PPTXParagraphElement, PPTXCalloutElement)):
            values = [element.content]
        elif isinstance(element, PPTXBulletsElement):
            values = element.items
        elif isinstance(element, (PPTXTableElement, PPTXMetricElement)):
            values = [element.content]
        elif isinstance(element, PPTXChartElement):
            values = [element.content]
        for value in values:
            references.extend(reference.model_dump(mode="json", exclude_none=True) for reference in value.source_references)
    return json.dumps(
        {
            "purpose": slide_content.purpose,
            "visual_guidance": slide_content.visual_guidance,
            "source_references": references,
            "provenance": provenance,
        },
        ensure_ascii=False,
        sort_keys=True,
    )


def _check_room(y, required_height, bottom) -> None:
    if y + required_height > bottom:
        raise ValueError("PPTX slide content exceeds the available slide area; reduce content or split the planned slide.")
